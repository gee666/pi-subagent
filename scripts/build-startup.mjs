import { build, transform } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = fileURLToPath(new URL("../", import.meta.url));

/** Keep module-relative assets and child entry URLs relative to the original source file. */
function sourceUrls(root) {
  return {
    name: "source-module-urls",
    setup(builder) {
      builder.onLoad({ filter: /\.[cm]?[jt]s$/ }, async ({ path: file }) => {
        const contents = await readFile(file, "utf8");
        if (!/\bimport\s*\.\s*meta\b/.test(contents)) return;
        const relative = "./" + path.relative(root, file).split(path.sep).map(encodeURIComponent).join("/");
        const result = await transform(contents, {
          loader: file.endsWith("ts") ? "ts" : "js",
          format: "esm",
          target: "node22",
          define: { "import.meta.url": "__subagentSourceUrl" },
          banner: `const __subagentSourceUrl = new URL(${JSON.stringify(relative)}, import.meta.url).href;`,
        });
        return { contents: result.code, loader: "js", resolveDir: path.dirname(file) };
      });
    },
  };
}

/** Bundle only local modules. Host SDK packages must be resolved by Pi's loader. */
export async function buildStartup({ root = packageRoot } = {}) {
  root = path.resolve(root);
  const result = await build({
    absWorkingDir: root,
    entryPoints: ["index.ts"],
    outfile: "startup.js",
    bundle: true,
    packages: "external",
    platform: "node",
    format: "esm",
    target: "node22",
    metafile: true,
    write: false,
    plugins: [sourceUrls(root)],
    banner: { js: "// Generated by npm run build. Edit the TypeScript sources, not this file." },
  });
  for (const input of Object.keys(result.metafile.inputs)) {
    const relative = path.relative(root, path.resolve(root, input));
    if (
      relative.startsWith(".." + path.sep) ||
      path.isAbsolute(relative) ||
      relative.split(path.sep).includes("node_modules")
    ) {
      throw new Error(`Startup bundles must contain only this package's source: ${input}`);
    }
  }
  await writeFile(path.join(root, "startup.js"), result.outputFiles[0].contents);
  return result.metafile;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const metadata = await buildStartup();
  console.error(
    `Built startup.js from ${Object.keys(metadata.inputs).length} local modules; package imports remain external.`,
  );
}
